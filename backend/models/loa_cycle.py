"""
LoaCycle model.

Represents a kickoff window for LOA submissions:
  - "normal"    : the regular quarterly validation cycle (admin sets start/end
                   dates; marketers can only Submit — not just save a draft —
                   while a normal cycle is active).
  - "emergency" : a fast-track window authorised by EMEA admins for urgent,
                   out-of-cycle LOAs. Kept isolated from the normal cycle's
                   summary Excel, but still counted in the yearly P&L total.

Lifecycle
---------
    draft → open → under_review → closed

  draft         cycle exists but has not started. Drafting is allowed,
                submission is not, and it is never the auto-assign target.
  open          the live window. New LOAs are auto-assigned here.
  under_review  submissions closed, reviewers are deciding. No new LOAs.
  closed        finished and frozen. Read-only everywhere; shows up under
                Past Cycles.

Only one *normal* cycle may be OPEN at a time — enforced by a partial unique
index (see migration `cycle_traceability`) so the rule holds even if a code
path forgets. Emergency cycles are exempt: one may run alongside a normal one.

`is_active` is retained as a derived mirror of `status == "open"` because older
endpoints and the tracker still read it. `status` is the source of truth.
"""
from sqlalchemy import Column, String, Boolean, DateTime, JSON
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.sql import func
import uuid

from backend.models.database import Base

# Lifecycle states, in order.
CYCLE_STATUSES = ("draft", "open", "under_review", "closed")

# States in which the cycle's data may still be modified.
CYCLE_EDITABLE_STATUSES = ("draft", "open", "under_review")


class LoaCycle(Base):
    __tablename__ = "loa_cycle"

    id          = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    name        = Column(String(120), nullable=False)          # e.g. "Cycle 3 2026"
    # Human-facing reference code — stable and immutable once set.
    # Format: {YEAR}-Q{Q}-N{seq} for normal, {YEAR}-EX{seq} for emergency.
    # Generated by the cycle_code_column migration; set on creation going forward.
    code        = Column(String(32), nullable=True, unique=True)
    cycle_type  = Column(String(20), nullable=False, default="normal")  # normal | emergency
    status      = Column(String(20), nullable=False, default="open")    # see CYCLE_STATUSES
    start_date  = Column(DateTime, nullable=False)
    end_date    = Column(DateTime, nullable=False)
    # Mirrors `status == "open"`. Kept for the tracker + /cycle/* endpoints.
    is_active   = Column(Boolean, default=True)
    # Actor emails — matches the existing convention on this table.
    created_by  = Column(String(255), nullable=True)
    created_at  = Column(DateTime, server_default=func.now())
    closed_at   = Column(DateTime, nullable=True)
    closed_by   = Column(String(255), nullable=True)
    # Throwaway cycle used to exercise the flow before go-live. Bannered in
    # the UI, and the only kind an admin is allowed to delete.
    is_test     = Column(Boolean, nullable=False, server_default="false", default=False)
    authorized_emails = Column(JSON, nullable=True)  # for emergency cycles: who can create under it
    # Why this cycle had to run off-schedule. Mandatory on emergency cycles —
    # going outside the normal window is an exception that has to be justified.
    emergency_reason = Column(String(500), nullable=True)

    @property
    def is_closed(self) -> bool:
        return self.status == "closed"

    @property
    def accepts_new_loas(self) -> bool:
        """Only an open cycle can receive newly created LOAs."""
        return self.status == "open"

    def apply_status(self, status: str) -> None:
        """Set the lifecycle state and keep the legacy is_active mirror in sync."""
        if status not in CYCLE_STATUSES:
            raise ValueError(f"unknown cycle status: {status}")
        self.status = status
        self.is_active = status == "open"

    def __repr__(self):
        return (f"<LoaCycle {self.name} ({self.cycle_type}) "
                f"{self.start_date}->{self.end_date} status={self.status}>")
